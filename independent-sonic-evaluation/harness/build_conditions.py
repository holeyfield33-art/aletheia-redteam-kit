"""Build frozen per-task materials for conditions A, B and C.

A  natural-language: interface.md + the score's requirement bullets (verbatim).
B  conventional structured: the same JSON plan with neutral naming
   (format 'structured-spec-v1', element kind 'todo' instead of 'hole'), a
   conventional scaffold with TODO markers, and a neutral handoff.
C  Sonic Code Studio: the bundle produced by the ORIGINAL sonic_templates
   write_project() (repo/, score.json, template.wav, events.json, AGENT_HANDOFF.md).

B is derived mechanically from the same score so B and C carry the same
structural information; only naming, audio artifacts and Sonic wording differ.
Output: TASKS/<task>/conditions/{A,B,C}/ with materials.md (inlined in the prompt)
and workspace/ (copied into each attempt's fresh workspace).
"""

import copy
import json
import shutil

from common import TASK_IDS, TASKS, load_score, sonic, write_json

SONIC_DOCSTRING = "Generated from an audible template. Verify behavior before use."
NEUTRAL_DOCSTRING = "Scaffold. Verify behavior before use."

NEUTRAL_HANDOFF = """# Implement this Python scaffold

The accompanying spec.json is the exact structural plan.

Fill only the TODO placeholders. Preserve module paths, function
signatures, imports, required expressions, branch/loop nesting and statement
order. Each TODO lists its allowed calls. If a requirement cannot be met within
this plan, explain the conflict and propose an explicit spec revision.
Do not silently remove a check or widen the allowed calls/imports.

Run behavioral tests for the stated requirements. A structural comparison
checks syntax; passing it does not prove behavior, security or correctness.

## Requirements

"""


def requirements(score):
    return list(score["requirements"]) + [r for m in score["modules"] for f in m["functions"] for r in f["requirements"]]


def neutral_spec(score):
    spec = copy.deepcopy(score)
    spec["format"] = "structured-spec-v1"

    def walk(body):
        for node in body:
            if node["kind"] == "hole":
                node["kind"] = "todo"
            for key in ("body", "otherwise"):
                if key in node:
                    walk(node[key])
    for module in spec["modules"]:
        for function in module["functions"]:
            walk(function["body"])
    return spec


def neutral_source(source):
    return source.replace(SONIC_DOCSTRING, NEUTRAL_DOCSTRING).replace("__SONIC_HOLE__:", "TODO:")


def build(task):
    s = sonic()
    score = load_score(task)
    base = TASKS / task / "conditions"
    if base.exists():
        shutil.rmtree(base)
    reqs = requirements(score)

    # Condition C: the original generator, unmodified.
    c_ws = base / "C" / "workspace"
    s["compiler"].write_project(score, c_ws)
    handoff_c = (c_ws / "AGENT_HANDOFF.md").read_text(encoding="utf-8")
    score_text = (c_ws / "score.json").read_text(encoding="utf-8")
    materials_c = ("## Materials (Sonic Code Studio build bundle)\n\n"
                   "Your workspace contains the bundle generated by Sonic Code Studio: AGENT_HANDOFF.md, score.json, "
                   "repo/ (the generated scaffold to fill in place), template.wav and events.json.\n\n"
                   "### AGENT_HANDOFF.md\n\n" + handoff_c + "\n### score.json\n\n```json\n" + score_text + "\n```\n")
    (base / "C" / "materials.md").write_text(materials_c, encoding="utf-8")

    # Condition B: same plan, neutral wording, conventional TODO scaffold, no audio.
    b_ws = base / "B" / "workspace"
    (b_ws / "repo").mkdir(parents=True)
    sources = s["compiler"].compile_score(score)
    neutral_sources = {path: neutral_source(src) for path, src in sources.items()}
    for path, src in neutral_sources.items():
        (b_ws / "repo" / path).write_text(src, encoding="utf-8", newline="\n")
    spec = neutral_spec(score)
    spec_text = json.dumps(spec, indent=2, ensure_ascii=False)
    (b_ws / "spec.json").write_text(spec_text, encoding="utf-8")
    handoff_b = (NEUTRAL_HANDOFF + "\n".join("- " + r for r in reqs) + "\n\n## Exact scaffold\n\n"
                 + "\n".join(f"### {path}\n\n```python\n{src}```\n" for path, src in neutral_sources.items()))
    (b_ws / "HANDOFF.md").write_text(handoff_b, encoding="utf-8")
    materials_b = ("## Materials (structured specification and scaffold)\n\n"
                   "Your workspace contains HANDOFF.md, spec.json and repo/ (the scaffold to fill in place).\n\n"
                   "### HANDOFF.md\n\n" + handoff_b + "\n### spec.json\n\n```json\n" + spec_text + "\n```\n")
    (base / "B" / "materials.md").write_text(materials_b, encoding="utf-8")

    # Condition A: English only, same requirement bullets, empty repo/.
    a_ws = base / "A" / "workspace"
    (a_ws / "repo").mkdir(parents=True)
    interface = (TASKS / task / "interface.md").read_text(encoding="utf-8")
    materials_a = ("## Task (natural-language specification)\n\n" + interface + "\n## Requirements\n\n"
                   + "\n".join("- " + r for r in reqs) + "\n")
    (base / "A" / "materials.md").write_text(materials_a, encoding="utf-8")

    sizes = {}
    for cond in "ABC":
        ws = base / cond / "workspace"
        files = [p for p in ws.rglob("*") if p.is_file()]
        sizes[cond] = {"materials_chars": len((base / cond / "materials.md").read_text(encoding="utf-8")),
                       "workspace_bytes": sum(p.stat().st_size for p in files),
                       "workspace_text_bytes": sum(p.stat().st_size for p in files if p.suffix != ".wav"),
                       "workspace_files": sorted(str(p.relative_to(ws)) for p in files)}
    return sizes


def main():
    summary = {task: build(task) for task in TASK_IDS}
    write_json(TASKS / "_condition_sizes.json", summary)
    for task, sizes in summary.items():
        print(task, {c: (v["materials_chars"], v["workspace_text_bytes"]) for c, v in sizes.items()})


if __name__ == "__main__":
    main()
